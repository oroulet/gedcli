use std::collections::HashSet;
use std::fmt::Write as _;

use gedcomkit::Node;

use crate::card::{self, Card, Event};
use crate::person::{Brief, People};
use crate::relatives::Rel;

const STYLE: &str = include_str!("html.css");

/// A static page: a tree diagram of the relatives, then every person in it with all their details and notes.
pub fn page(
    people: &People,
    root: &Brief,
    ancestors: Option<&Rel>,
    descendants: Option<&Rel>,
) -> String {
    let order = people_in_order(ancestors, descendants);
    let on_page: HashSet<String> = order.iter().map(|id| id.to_ascii_uppercase()).collect();
    let mut out = String::new();
    let title = format!("Family tree of {}", root.name);
    let _ = write!(
        out,
        "<!doctype html>\n<html lang=\"fr\">\n<head>\n<meta charset=\"utf-8\">\n\
         <meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n\
         <title>{}</title>\n<style>\n{STYLE}</style>\n</head>\n<body>\n<header><h1>{}</h1>\
         <p class=\"muted\">{} people · generated by gedcli</p></header>\n",
        esc(&title),
        esc(&title),
        order.len()
    );
    out.push_str("<nav class=\"diagram\">\n");
    if let Some(rel) = ancestors {
        let _ = writeln!(
            out,
            "<div class=\"tree up\"><ul>{}</ul></div>",
            ancestor_item(rel)
        );
    }
    if let Some(rel) = descendants {
        let joined = if ancestors.is_some() { " joined" } else { "" };
        let _ = writeln!(
            out,
            "<div class=\"tree{joined}\"><ul>{}</ul></div>",
            descendant_item(rel)
        );
    }
    out.push_str("</nav>\n<main>\n");
    for id in &order {
        if let Some(record) = people.record(id) {
            out.push_str(&person_section(people, record, &on_page));
        }
    }
    out.push_str("</main>\n</body>\n</html>\n");
    out
}

fn people_in_order(ancestors: Option<&Rel>, descendants: Option<&Rel>) -> Vec<String> {
    let mut order = Vec::new();
    let mut seen = HashSet::new();
    let mut add = |brief: &Brief| {
        if seen.insert(brief.id.to_ascii_uppercase()) {
            order.push(brief.id.clone());
        }
    };
    let mut level: Vec<&Rel> = ancestors.into_iter().chain(descendants).collect();
    while !level.is_empty() {
        let mut next = Vec::new();
        for rel in level {
            add(&rel.person);
            next.extend(rel.parents.iter());
            for family in &rel.families {
                if let Some(partner) = &family.partner {
                    add(partner);
                }
                next.extend(family.children.iter());
            }
        }
        level = next;
    }
    order
}

fn ancestor_item(rel: &Rel) -> String {
    let parents: String = rel.parents.iter().map(ancestor_item).collect();
    let list = if parents.is_empty() {
        String::new()
    } else {
        format!("<ul>{parents}</ul>")
    };
    format!(
        "<li>{}{list}</li>",
        tree_card(&rel.person, None, rel.repeat)
    )
}

fn descendant_item(rel: &Rel) -> String {
    match rel.families.as_slice() {
        [only] => {
            let children: String = only.children.iter().map(descendant_item).collect();
            let list = if children.is_empty() {
                String::new()
            } else {
                format!("<ul>{children}</ul>")
            };
            format!(
                "<li>{}{list}</li>",
                tree_card(&rel.person, only.partner.as_ref(), rel.repeat)
            )
        }
        families => {
            let unions: String = families
                .iter()
                .map(|family| {
                    let partner = family
                        .partner
                        .as_ref()
                        .map_or_else(|| "unknown partner".to_owned(), |p| p.name.clone());
                    let children: String = family.children.iter().map(descendant_item).collect();
                    let list = if children.is_empty() {
                        String::new()
                    } else {
                        format!("<ul>{children}</ul>")
                    };
                    format!(
                        "<li><span class=\"card union\">⚭ {}</span>{list}</li>",
                        esc(&partner)
                    )
                })
                .collect();
            let list = if unions.is_empty() {
                String::new()
            } else {
                format!("<ul>{unions}</ul>")
            };
            format!(
                "<li>{}{list}</li>",
                tree_card(&rel.person, None, rel.repeat)
            )
        }
    }
}

fn tree_card(person: &Brief, partner: Option<&Brief>, repeat: bool) -> String {
    let mut html = format!(
        "<a class=\"card {}\" href=\"#{}\"><b>{}{}</b>",
        person.sex.as_deref().unwrap_or("U"),
        anchor(&person.id),
        if repeat { "↺ " } else { "" },
        esc(&person.name)
    );
    for line in [&person.life, &person.info].into_iter().flatten() {
        let _ = write!(html, "<small>{}</small>", esc(line));
    }
    if let Some(partner) = partner {
        let _ = write!(
            html,
            "<small class=\"partner\">⚭ {}</small>",
            esc(&partner.name)
        );
    }
    html.push_str("</a>");
    html
}

fn person_section(people: &People, record: &Node, on_page: &HashSet<String>) -> String {
    let card = card::build(people, record);
    let mut out = format!(
        "<section id=\"{}\" class=\"person {}\">\n<h2>{}</h2>\n",
        anchor(&card.person.id),
        record.value_of("SEX").unwrap_or_default(),
        esc(&card.person.name)
    );
    if let Some(life) = &card.person.life {
        let _ = writeln!(out, "<p class=\"life\">{}</p>", esc(life));
    }
    out.push_str("<dl>\n");
    facts(&mut out, &card);
    relatives(&mut out, &card, on_page);
    out.push_str("</dl>\n");
    for note in &card.notes {
        let _ = writeln!(
            out,
            "<blockquote class=\"note\">{}</blockquote>",
            esc(note).replace('\n', "<br>\n")
        );
    }
    footer(&mut out, people, record, &card);
    out.push_str("</section>\n");
    out
}

fn facts(out: &mut String, card: &Card) {
    if let Some(sex) = &card.sex {
        row(out, "Sex", &esc(sex));
    }
    if card.names.len() > 1 {
        row(
            out,
            "Names",
            &card
                .names
                .iter()
                .map(|n| esc(n))
                .collect::<Vec<_>>()
                .join("<br>"),
        );
    }
    for event in &card.events {
        row(out, &event.label, &event_text(event));
    }
    for contact in &card.contacts {
        row(out, "Contact", &esc(contact));
    }
}

fn relatives(out: &mut String, card: &Card, on_page: &HashSet<String>) {
    for parent in &card.parents {
        row(
            out,
            &capitalized(&parent.relation),
            &link(&parent.person, on_page),
        );
    }
    for family in &card.families {
        let partner = family
            .partner
            .as_ref()
            .map_or_else(|| "unknown partner".to_owned(), |p| link(p, on_page));
        let marriage: Vec<String> = family
            .events
            .iter()
            .map(|e| format!("{}: {}", esc(&e.label), event_text(e)))
            .collect();
        let extra = if marriage.is_empty() {
            String::new()
        } else {
            format!(" <span class=\"muted\">({})</span>", marriage.join("; "))
        };
        row(out, "Partner", &format!("{partner}{extra}"));
        let children: Vec<String> = family
            .children
            .iter()
            .map(|c| link(&c.person, on_page))
            .collect();
        if !children.is_empty() {
            row(out, "Children", &children.join(", "));
        }
    }
}

fn footer(out: &mut String, people: &People, record: &Node, card: &Card) {
    let mut lines = Vec::new();
    let sources: Vec<String> = record
        .all("SOUR")
        .filter_map(|s| s.pointer())
        .filter_map(|p| people.record(p))
        .filter_map(|s| s.value_of("TITL"))
        .map(|t| esc(&t))
        .collect();
    if !sources.is_empty() {
        lines.push(format!("Sources: {}", sources.join("; ")));
    }
    for file in &card.media {
        let shown = file
            .split('?')
            .next()
            .unwrap_or(file)
            .rsplit('/')
            .next()
            .unwrap_or(file);
        lines.push(format!(
            "Media: <a href=\"{}\">{}</a>",
            esc(file),
            esc(shown)
        ));
    }
    let mut about = vec![esc(&card.person.id)];
    about.extend(card.ids.iter().map(|i| esc(i)));
    about.extend(card.added_by.iter().map(|a| format!("added by {}", esc(a))));
    about.extend(card.changed.iter().map(|c| format!("changed {}", esc(c))));
    lines.push(about.join(" · "));
    let _ = writeln!(
        out,
        "<footer class=\"muted\">{}</footer>",
        lines.join("<br>")
    );
}

fn event_text(event: &Event) -> String {
    [&event.value, &event.date, &event.place, &event.cause]
        .into_iter()
        .flatten()
        .map(|t| esc(t))
        .collect::<Vec<_>>()
        .join(" · ")
}

fn row(out: &mut String, label: &str, value_html: &str) {
    let _ = writeln!(out, "<dt>{}</dt><dd>{value_html}</dd>", esc(label));
}

fn link(person: &Brief, on_page: &HashSet<String>) -> String {
    let life = person
        .life
        .as_ref()
        .map(|l| format!(" <span class=\"muted\">({})</span>", esc(l)))
        .unwrap_or_default();
    if on_page.contains(&person.id.to_ascii_uppercase()) {
        format!(
            "<a href=\"#{}\">{}</a>{life}",
            anchor(&person.id),
            esc(&person.name)
        )
    } else {
        format!("{}{life}", esc(&person.name))
    }
}

fn anchor(xref: &str) -> String {
    xref.trim_matches('@')
        .chars()
        .filter(|c| c.is_ascii_alphanumeric() || *c == '_')
        .collect()
}

fn capitalized(word: &str) -> String {
    let mut chars = word.chars();
    chars
        .next()
        .map(|c| c.to_uppercase().chain(chars).collect())
        .unwrap_or_default()
}

fn esc(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}
